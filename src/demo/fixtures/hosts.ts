type Seed = Partial<Host> &
  Pick<Host, "id" | "name" | "ip" | "username" | "folder"> & {
    parentHostId?: number | null;
    online?: boolean;
    features?: Record<string, Record<string, unknown>>;
  };

const created = "2026-08-14T09:12:00.000Z";

function host(seed: Seed): Host & { parentHostId: number | null } {
  const { features = {}, online: _online, ...rest } = seed;
  return {
    port: 22,
    sshPort: 22,
    tags: [],
    pin: false,
    authType: "credential",
    enableSsh: true,
    connectionType: "ssh",
    statusCheckEnabled: true,
    statusCheckInterval: null,
    jumpHosts: [],
    socks5ProxyChain: [],
    portKnockSequence: [],
    notes: "",
    userId: DEMO_USER_ID,
    createdAt: created,
    updatedAt: created,
    hasPassword: false,
    hasKey: false,
    hasKeyPassword: false,
    hasSudoPassword: false,
    localOnly: false,
    sharedCopy: false,
    isShared: false,
    parentHostId: null,
    protocolAuth: {},
    defaultOverrides: null,
    syncId: `demo-host-${seed.id}`,
    ...rest,
    pluginSettings: {
      "ssh-terminal": { enableTerminal: true, enableCommandHistory: true },
      "file-manager": { enableFileManager: true },
      "host-metrics": { metricsEnabled: true },
      ...features,
    },
  } as Host & { parentHostId: number | null };
}

